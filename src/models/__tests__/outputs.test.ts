import {
  type ClassifyTaskOutput,
  type SpanTaskOutput,
  validateComprehendResults,
  validateExtractResults,
  validateExtractRelationsResults,
  validateExtractSummaryResults,
  validateInstructItResults,
} from '../outputs';

describe('Outputs Validation', () => {
  describe('validateExtractRelationsResults', () => {
    const sampleRelation = {
      source: {
        span: 'Tim Cook',
        entity: 'person',
        start: 0,
        end: 8,
        score: 0.99,
      },
      relation: 'leads',
      target: {
        span: 'Apple',
        entity: 'organization',
        start: 15,
        end: 20,
        score: 0.98,
      },
      score: 0.95,
    };

    it('should parse server { outputs: [...] } structure', () => {
      const serverResponse = {
        outputs: [sampleRelation],
      };

      const parsed = validateExtractRelationsResults(serverResponse);
      expect(parsed.outputs).toHaveLength(1);
      expect(parsed.outputs[0].relation).toBe('leads');
      expect(parsed.outputs[0].source.span).toBe('Tim Cook');
      expect(parsed.outputs[0].target.span).toBe('Apple');
    });

    it('should parse empty outputs array', () => {
      expect(validateExtractRelationsResults({ outputs: [] })).toEqual({ outputs: [] });
    });

    it('should throw when outputs is not valid', () => {
      expect(() => validateExtractRelationsResults({ invalid: 123 })).toThrow();
      expect(() =>
        validateExtractRelationsResults({
          outputs: [{ invalid: 'item' }],
        }),
      ).toThrow();
    });
  });

  describe('validateExtractResults', () => {
    it('should parse task dictionary under outputs', () => {
      const parsed = validateExtractResults({
        outputs: {
          entities: {
            type: 'span',
            value: [
              {
                span: 'Apple',
                entity: 'organization',
                start: 0,
                end: 5,
                score: 0.97,
              },
            ],
          },
        },
      });

      const entities = parsed.entities as SpanTaskOutput;
      expect(entities).toBeDefined();
      expect(entities.value).toHaveLength(1);
      expect(entities.value[0].text).toBe('Apple');
      expect(entities.value[0].span).toBe('Apple');
      expect(entities.value[0].label).toBe('organization');
      expect(entities.value[0].entity).toBe('organization');
    });

    it('should throw when outputs is a list/array', () => {
      expect(() =>
        validateExtractResults({
          outputs: [{ span: 'Apple', entity: 'org' }],
        }),
      ).toThrow("Unexpected response shape: expected task-keyed dictionary in 'outputs'");
    });

    it('should throw when data is not an object or missing outputs', () => {
      expect(() => validateExtractResults(null)).toThrow();
      expect(() => validateExtractResults('not-an-object')).toThrow();
      expect(() => validateExtractResults({ other: 'field' })).toThrow();
    });
  });

  describe('validateComprehendResults', () => {
    it('should parse task dictionary under outputs', () => {
      const parsed = validateComprehendResults({
        outputs: {
          topic: {
            type: 'classify',
            value: 'technology',
            scores: { technology: 0.92 },
          },
        },
      });

      const topic = parsed.topic as ClassifyTaskOutput;
      expect(topic).toBeDefined();
      expect(topic.value).toBe('technology');
      expect(topic.scores?.technology).toBe(0.92);
      expect(parsed.outputs.topic).toBeDefined();
    });

    it('should throw when outputs is a list/array', () => {
      expect(() =>
        validateComprehendResults({
          outputs: [{ label: 'technology', score: 0.92 }],
        }),
      ).toThrow("Unexpected response shape: expected task-keyed dictionary in 'outputs'");
    });

    it('should throw when data is not an object or missing outputs', () => {
      expect(() => validateComprehendResults(null)).toThrow();
      expect(() => validateComprehendResults('not-an-object')).toThrow();
      expect(() => validateComprehendResults({ other: 'field' })).toThrow();
    });
  });

  describe('validateExtractSummaryResults', () => {
    it('should parse summary results array', () => {
      const parsed = validateExtractSummaryResults({
        outputs: [
          {
            text: 'Key sentence summary.',
            start: 0,
            end: 21,
            score: 0.88,
          },
        ],
      });

      expect(parsed.outputs).toHaveLength(1);
      expect(parsed.outputs[0].text).toBe('Key sentence summary.');
    });
  });

  describe('validateInstructItResults', () => {
    it('should parse string outputs', () => {
      const parsed = validateInstructItResults({
        outputs: 'Summary generated by instruction model.',
      });

      expect(parsed.outputs).toBe('Summary generated by instruction model.');
    });

    it('should parse record or array outputs with optional parsed boolean', () => {
      const objectParsed = validateInstructItResults({
        outputs: { summary: 'text', items: [1, 2, 3] },
        parsed: true,
      });

      expect(objectParsed.outputs).toEqual({ summary: 'text', items: [1, 2, 3] });
      expect(objectParsed.parsed).toBe(true);

      const arrayParsed = validateInstructItResults({
        outputs: ['item1', 'item2'],
      });

      expect(arrayParsed.outputs).toEqual(['item1', 'item2']);
    });
  });
});
